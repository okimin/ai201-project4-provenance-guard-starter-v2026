SCENARIOS = [
    {
        "name": "my own writing",
        "criterion": 1,
        "texts": OWN_WRITING,
    },
    {
        "name": "score spread",
        "criterion": 2,
        # First three clearly AI, last three clearly human.
        "texts": CLEARLY_AI + CLEARLY_HUMAN,
    },
    {
        "name": "appeal path",
        "criterion": 3,
        # Ten real submissions to appeal. The attack set's false-positive rows
        # are human writing, which is exactly who appeals, plus two samples.
        "appeals": [_attack(f"FP0{i}") for i in range(1, 9)]
                   + [_sample("clearly_ai"), _sample("borderline")],
        "unknown_ids": ["c_doesnotexist", "c_000000000000"],
        "reasoning": "I wrote this myself and would like a person to review it.",
    },
    {
        "name": "label coverage",
        "criterion": 4,
        # Order: 3 clearly AI, 3 borderline, 3 clearly human.
        "texts": CLEARLY_AI + BORDERLINE + CLEARLY_HUMAN,
    },
    {
        "name": "bad input",
        "criterion": 5,
        "check_log": True,
        "bodies": [
            {"creator_id": "eval_bad_missing"},               # no text field
            {"text": "", "creator_id": "eval_bad_empty"},
            {"text": None, "creator_id": "eval_bad_null"},
            {"text": "word " * 20000, "creator_id": "eval_bad_huge"},  # 100,000 chars
        ],
    },
]


def validate() -> list[str]:
    """
    Complain about anything malformed, before a long run rather than during.

    A "bodies" scenario is deliberately exempt from the empty check — an empty
    string is the whole point of a bad-input case, and refusing to run one
    would make that criterion untestable.
    """
    problems = []
    for i, scenario in enumerate(SCENARIOS, 1):
        if not scenario.get("name"):
            problems.append(f"scenario {i} has no name")

        texts = scenario.get("texts") or scenario.get("appeals")
        bodies = scenario.get("bodies")

        if texts and bodies:
            problems.append(
                f"scenario {i} ('{scenario.get('name')}') has both texts and "
                f"bodies — pick one"
            )
            continue

        if bodies:
            for j, body in enumerate(bodies, 1):
                if not isinstance(body, dict):
                    problems.append(
                        f"scenario {i}, body {j} is not a dict — bodies are whole "
                        f"request bodies, like {{'text': '', 'creator_id': 'x'}}"
                    )
            continue

        if not texts:
            problems.append(f"scenario {i} has no texts and no bodies")
            continue

        for j, text in enumerate(texts, 1):
            if not str(text).strip():
                problems.append(
                    f"scenario {i}, text {j} is empty — if an empty submission is what "
                    f"you're testing, use 'bodies' instead of 'texts'"
                )
            elif str(text).startswith("REPLACE ME"):
                problems.append(
                    f"scenario {i} ('{scenario.get('name')}'), text {j} is still "
                    f"the placeholder"
                )
    return problems
