"""
What your test runs. ← UNIT 8, MILESTONE 3

One scenario per criterion in criteria.md. `run_eval.py` runs each one three
times. Where the inputs come from:

  1. My own writing     — ten pieces I wrote myself (OWN_WRITING below).
  2. Score spread       — the three clearly-AI and three clearly-human inputs
                          from criterion 4, scored on their own.
  3. Appeal path        — ten real submissions, each appealed against the
                          content_id that came back, plus two made-up ids.
                          run_eval.py was extended to do this ("appeals").
  4. Label coverage     — nine calibration inputs: three clearly AI, three
                          borderline, three clearly human.
  5. Bad input          — the four bodies criteria.md names, sent exactly as
                          written, with the newest log line checked after each
                          ("check_log").

A scenario carries one of:

    "texts"    strings, each sent as {"text": ..., "creator_id": ...}
    "bodies"   whole request bodies, sent exactly as written
    "appeals"  strings to submit and then appeal (criterion 3 only)
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def _sample(name):
    return json.loads((ROOT / "samples" / f"{name}.json").read_text())["text"]


def _attack(attack_id):
    with open(ROOT / "attack_set" / "attacks.csv", newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["id"] == attack_id:
                return row["text"]
    raise KeyError(attack_id)


# ── Criterion 1: my own writing ──────────────────────────────────────────────
# Ten pieces I actually wrote. Not AI text, not something from the web.
# Stored word for word in samples/own_writing.json, in this order:
#   1 Stripe cover letter      2 Twilio cover letter     3 video-brief instructions
#   4 CECC bio (third person)  5 Inca/Cuzco report       6 Yuanming Yuan essay
#   7 SHPE recommendation      8 coding-contest rules    9 LAESA bio
#  10 STEM Hive Facebook post
OWN_WRITING = json.loads((ROOT / "samples" / "own_writing.json").read_text(encoding="utf-8"))

# ── Calibration inputs for criteria 2 and 4 ──────────────────────────────────
# Clearly AI: the sample, plus two paragraphs generated by an AI model (Claude)
# in the same generic, even register.
